def expand_cases(json_path: Path = Path(__file__).resolve().parent / "data" / "cases.json"):
    """Load existing cases, add new ones, write back to file."""
    # Load existing
    with open(json_path, "r", encoding="utf-8") as f:
        existing = json.load(f)

    print(f"Loaded {len(existing)} existing cases")

    # Append new
    existing.extend(NEW_CASES)

    print(f"Appended {len(NEW_CASES)} new cases")

    # Write back
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(existing, f, indent=2, ensure_ascii=False)

    print(f"Saved total of {len(existing)} cases to {json_path}")
    return len(existing)


